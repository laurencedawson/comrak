type AstNode<'a> = Node<'a, RefCell<Ast<'a>>>;

const HEADER_SIZE: usize = 8;
const MAX_URL_LEN: usize = 4095;

/// Count UTF-16 code units from a UTF-8 string.
#[inline]
fn utf16_len(s: &str) -> usize {
    let mut len = 0;
    for &b in s.as_bytes() {
        if (b & 0b1100_0000) != 0b1000_0000 {
            len += 1;
        }
        if (b & 0b1111_1000) == 0b1111_0000 {
            len += 1;
        }
    }
    len
}

/// Render a comrak AST into a binary blob, a link to one of `site`'s own pages written as an
/// `APP_LINK` ([`sites::PLAIN`] owns none).
///
/// Returns `None` if the document has no spans and text is unchanged from input
/// (caller should use the raw input string directly).
pub fn render_blob<'a>(root: &'a AstNode<'a>, input: &str, site: u8) -> Option<Vec<u8>> {
    render(input, site, |b| {
        visit(root, b);
        b.append_footnotes();
    })
}

/// Renders `input` through `walk`, for both walks: with the ASCII fast path where the input is
/// ASCII, and again without it where the text came out otherwise. One upfront SIMD `is_ascii` on
/// the input replaces thousands of small per-node scans inside `write_text`, but is only a hint:
/// a decoded entity, a shortcode emoji or a typographic symbol writes non-ASCII from ASCII input,
/// and the fast path counted bytes as UTF-16 units, so every span offset needs redoing, not just
/// the flag. `None` where the document has no spans and its text is the input.
fn render(input: &str, site: u8, walk: impl Fn(&mut BlobWriter)) -> Option<Vec<u8>> {
    let mut b = BlobWriter::new(input.len(), input.is_ascii(), site);
    walk(&mut b);
    if b.fast_path_ascii && !b.text().is_ascii() {
        b = BlobWriter::new(input.len(), false, site);
        walk(&mut b);
    }
    (!b.spans.is_empty() || b.text() != input).then(|| b.into_blob())
}

pub(crate) struct BlobWriter {
    blob: Vec<u8>,
    pub(crate) spans: Vec<i32>,
    pub(crate) url_data: Vec<u8>,
    footnotes: Vec<String>,
    len: usize,
    p: usize,
    /// Set if every byte written to the text section is ASCII (< 0x80).
    /// Stored as a header flag so consumers can skip their own scan.
    all_ascii: bool,
    /// When true, every `write_text` input is assumed ASCII (because the
    /// original markdown is ASCII), letting `write_text` skip the per-call
    /// `is_ascii` SIMD scan on long ASCII docs. `render_blob` verifies the
    /// assumption against the finished text; parser transforms that break
    /// it (smartypants, entities, emoji) trigger a slow-path re-render.
    fast_path_ascii: bool,
    /// Set if any LEMMY_SPOILER_CONTENT span exists. Stored as a header flag so
    /// consumers can skip hidden-spoiler containment checks for normal content.
    has_spoiler_body: bool,
    /// How many lists and quotes the walk is inside.
    list_depth: usize,
    quote_depth: usize,
    /// The site the input is from, which knows its own pages: a link to one is an `APP_LINK`.
    site: u8,
}

impl BlobWriter {
    /// A writer for `cap` bytes of input from `site`. With `fast_path_ascii`, every `write_text`
    /// is taken as ASCII and skips its scan; `render` checks the finished text and renders again
    /// without it where a transform broke that.
    pub(crate) fn new(cap: usize, fast_path_ascii: bool, site: u8) -> Self {
        let mut blob = Vec::with_capacity(HEADER_SIZE + cap);
        blob.extend_from_slice(&[0u8; HEADER_SIZE]);
        // Pre-size spans/url_data to skip the doubling chain from 0. spans
        // holds 4 i32 per span; budget ~1 span per 40 input bytes (typical
        // density across the bench corpus). url_data is bytes; budget ~1
        // byte per 32 input bytes. Below ~96 chars the doc is too small to
        // make pre-allocation worthwhile (plain text has zero spans); leave
        // both at zero capacity, which std::vec::Vec specializes to no
        // allocation. Both clamp at the top to keep pathological input from
        // requesting megabytes up front.
        let (spans_cap, url_cap) = if cap < 96 {
            (0, 0)
        } else {
            ((cap / 40).min(2048) * 4, (cap / 32).min(8192))
        };
        Self {
            blob,
            spans: Vec::with_capacity(spans_cap),
            url_data: Vec::with_capacity(url_cap),
            footnotes: vec![],
            len: 0,
            p: 0,
            all_ascii: true,
            fast_path_ascii,
            has_spoiler_body: false,
            site,
            list_depth: 0,
            quote_depth: 0,
        }
    }

    #[inline]
    pub(crate) fn pos(&self) -> usize {
        self.len + self.p
    }

    #[inline]
    pub(crate) fn write_text(&mut self, s: &str) {
        if self.p > 0 {
            self.blob.extend(std::iter::repeat_n(b'\n', self.p));
            self.len += self.p;
            self.p = 0;
        }
        self.blob.extend_from_slice(s.as_bytes());
        if self.fast_path_ascii {
            // Assumed ASCII: `all_ascii` stays true and byte length equals
            // UTF-16 length. `render_blob` checks the assumption against
            // the finished text; a violation discards this writer entirely.
            self.len += s.len();
            return;
        }
        let ascii = s.is_ascii();
        self.all_ascii &= ascii;
        self.len += if ascii { s.len() } else { utf16_len(s) };
    }

    pub(crate) fn nl(&mut self, n: usize) {
        self.p = self.p.max(n);
    }

    /// `write_text` for author prose (Text nodes): applies the typographic
    /// symbol substitution. A substitution always introduces non-ASCII; when
    /// everything written so far is genuinely ASCII the accumulated UTF-16
    /// length is still exact, so the writer can drop the fast path in place
    /// and skip the re-render. Decoded entities and shortcode emoji break
    /// that premise — they write non-ASCII under fast byte-as-unit accounting
    /// — so with a dirty prefix the flag stays set and the final scan in
    /// `render_blob` re-renders with exact accounting, as it did before
    /// symbols moved here.
    fn write_prose(&mut self, s: &str) {
        // One gate for both character passes: prefer_ascii only acts on
        // 0xE2-lead sequences, typographic_symbols only on '(' or '+'.
        // The common clean node takes a single scan and writes as-is.
        if memchr::memchr3(0xE2, b'(', b'+', s.as_bytes()).is_none() {
            return self.write_text(s);
        }
        let s = prefer_ascii(s);
        match typographic_symbols(&s) {
            Cow::Borrowed(_) => self.write_text(&s),
            Cow::Owned(sym) => {
                if !self.fast_path_ascii || self.text().is_ascii() {
                    self.fast_path_ascii = false;
                }
                self.write_text(&sym);
            }
        }
    }

    /// True if the next byte written would land at the start of a line.
    /// Either nothing has been written, the last byte is a newline, or
    /// pending newlines are queued for flush.
    pub(crate) fn at_line_start(&self) -> bool {
        self.p > 0 || self.len == 0 || self.blob.last() == Some(&b'\n')
    }

    /// Rendered text bytes so far (excluding header). Used during render and by tests.
    pub(crate) fn text(&self) -> &str {
        // Only `&str` slices and newlines are ever written past the header, so the bytes are UTF-8 by construction
        unsafe { std::str::from_utf8_unchecked(&self.blob[HEADER_SIZE..]) }
    }

    pub(crate) fn span(&mut self, t: i32, start: usize) {
        self.span_data(t, start, 0);
    }

    pub(crate) fn span_data(&mut self, t: i32, start: usize, data: i32) {
        if start < self.len {
            self.spans
                .extend_from_slice(&[start as i32, self.len as i32, t, data]);
            self.has_spoiler_body |= t == LEMMY_SPOILER_CONTENT;
        }
    }

    pub(crate) fn span_url(&mut self, t: i32, start: usize, url: &ResolvedUrl) {
        if start >= self.len {
            return;
        }
        // Takes only a ResolvedUrl, so no caller can emit a raw URL and none is resolved twice.
        let offset = self.url_data.len();
        // Back a capped cut off to a char boundary; the host decodes this slice as UTF-8.
        let mut url_len = url.len().min(MAX_URL_LEN);
        while !url.is_char_boundary(url_len) {
            url_len -= 1;
        }
        self.url_data.extend_from_slice(&url.as_bytes()[..url_len]);
        self.spans.extend_from_slice(&[
            start as i32,
            self.len as i32,
            t,
            ((offset as i32) << 12) | (url_len as i32),
        ]);
    }

    /// Emit a TABLE span whose cells are packed into `url_data` and addressed by
    /// `data = offset + 1` (0 stays reserved for a legacy/no-table placeholder).
    /// Payload: `[ (rows<<16 | cols):u32 ] [ (len:u16)(utf8) x rows*cols ]`, cells
    /// row-major as inline markdown for the UI to re-parse. Self-delimiting, so no
    /// length cap.
    pub(crate) fn span_table<'a>(&mut self, start: usize, node: &'a AstNode<'a>) {
        if start >= self.len {
            return;
        }
        let cols = match &node.data.borrow().value {
            Table(nt) => nt.num_columns.min(0xFFFF),
            _ => return,
        };
        let opts = crate::Options::default();
        let rows = (node.children().count() as u32).min(0xFFFF);
        let offset = self.url_data.len();
        let packed = (rows << 16) | cols as u32;
        self.url_data.extend_from_slice(&packed.to_le_bytes());
        for row in node.children().take(rows as usize) {
            // Each row writes exactly `cols` cells: its own, padded with empties. A cell's markdown is
            // written straight after its length slot, trimmed in place, and the slot filled in after
            let mut written = 0;
            for cell in row.children().take(cols) {
                let slot = self.url_data.len();
                self.url_data.extend_from_slice(&[0, 0]);
                let start = self.url_data.len();
                for child in cell.children() {
                    let _ =
                        crate::cm::format_internal(child, &opts, &mut Utf8Sink(&mut self.url_data));
                    while self.url_data.last() == Some(&b'\n') {
                        self.url_data.pop();
                    }
                }
                let bytes = &self.url_data[start..];
                let (lead, total) = (
                    bytes.len() - bytes.trim_ascii_start().len(),
                    bytes.trim_ascii().len(),
                );
                let mut len = total.min(u16::MAX as usize);
                // Same char-boundary contract as span_url: cells decode as UTF-8.
                while len < total && self.url_data[start + lead + len] & 0xC0 == 0x80 {
                    len -= 1;
                }
                self.url_data
                    .copy_within(start + lead..start + lead + len, start);
                self.url_data.truncate(start + len);
                self.url_data[slot..slot + 2].copy_from_slice(&(len as u16).to_le_bytes());
                written += 1;
            }
            for _ in written..cols {
                self.url_data.extend_from_slice(&[0, 0]);
            }
        }
        self.spans
            .extend_from_slice(&[start as i32, self.len as i32, TABLE, (offset as i32) + 1]);
    }

    fn emit_image(&mut self, url: &ResolvedUrl) {
        if self.len != 0 {
            // Separate the image from prior content by at least two newlines;
            // existing trailing `\n` (past any trailing spaces/tabs) count.
            let existing = self.blob[HEADER_SIZE..]
                .iter()
                .rev()
                .skip_while(|&&b| matches!(b, b' ' | b'\t'))
                .take_while(|&&b| b == b'\n')
                .count();
            self.nl(2_usize.saturating_sub(existing));
        }
        let start = self.pos();
        self.write_text("\u{0001}");
        self.span_url(IMAGE, start, url);
        self.nl(2);
    }

    /// A link's spans over the words written since `start`: an `APP_LINK` where the url is one of
    /// the site's own pages, a `LINK` otherwise, with the domain after the words where they lack
    /// it, unless it is the site's own, which tells its reader nothing.
    fn link(&mut self, start: usize, text_start: usize, url: &ResolvedUrl<'_>) {
        let page = site::page(self.site, url);
        self.span_url(if page == Page::Own { APP_LINK } else { LINK }, start, url);
        self.span(LINK_SIZE, start);
        if page == Page::Elsewhere {
            self.append_domain_suffix(text_start, url);
        }
    }

    fn append_domain_suffix(&mut self, text_start: usize, url: &str) {
        let Some(domain) = extract_domain(url) else {
            return;
        };
        let needle = domain.as_bytes();
        if self.blob[text_start..]
            .windows(needle.len())
            .any(|w| w.eq_ignore_ascii_case(needle))
        {
            return;
        }
        self.write_text(" (");
        self.write_text(&domain);
        self.write_text(")");
    }

    pub(crate) fn append_footnotes(&mut self) {
        let notes = std::mem::take(&mut self.footnotes);
        if notes.is_empty() {
            return;
        }
        self.nl(2);
        let start = self.pos();
        self.write_text("\u{0001}");
        self.span(HRULE, start);
        self.nl(2);
        for (i, note) in notes.iter().enumerate() {
            let start = self.pos();
            self.write_text(&(i + 1).to_string());
            self.span(SUPERSCRIPT, start);
            self.span(SUPERSCRIPT_SIZE, start);
            self.write_text(" ");
            self.write_text(note);
            self.nl(1);
        }
    }

    pub(crate) fn into_blob(mut self) -> Vec<u8> {
        let txt_len = self.blob.len() - HEADER_SIZE;
        let span_count = self.spans.len() / 4;

        let spans_view = unsafe {
            let ptr = self.spans.as_mut_ptr() as *mut [i32; 4];
            std::slice::from_raw_parts_mut(ptr, span_count)
        };
        // Pack the sort key (start asc, end desc, type asc) into a single u64
        // so the comparator is a plain u64 compare instead of a 3-field tuple
        // walk. Layout: bits 63..32 = start, bits 31..8 = inverted 24-bit end
        // (for descending order), bits 7..0 = span type. Safe because start/end
        // are non-negative text offsets (well under 2^24 for all realistic
        // documents) and span types fit in u8.
        let key = |s: &[i32; 4]| {
            let start = s[0] as u32 as u64;
            let end_inv = (0xFF_FFFF - (s[1] as u32 & 0xFF_FFFF)) as u64;
            let ty = (s[2] as u32 & 0xFF) as u64;
            (start << 32) | (end_inv << 8) | ty
        };
        // Spans arrive after their node's children, so each only has to move back past its own
        // descendants: an insertion sort is linear plus those moves. Deep nesting could make the
        // moves quadratic, so past a budget per span the rest goes to the general sort.
        let mut budget = span_count * 8;
        let mut i = 1;
        while i < span_count && budget > 0 {
            let cur = spans_view[i];
            let k = key(&cur);
            let mut j = i;
            while j > 0 && key(&spans_view[j - 1]) > k {
                spans_view[j] = spans_view[j - 1];
                j -= 1;
            }
            budget = budget.saturating_sub(i - j);
            spans_view[j] = cur;
            i += 1;
        }
        if i < span_count {
            spans_view.sort_unstable_by_key(key);
        }

        // Header layout: text_len in bytes 0-3, span_count in bytes 4-6, flags
        // in byte 7. span_count is capped at 24 bits (16M); the high byte is
        // reused as a flag field so the header stays 8 bytes.
        //   bit 0: is_ascii         — text section is pure ASCII
        //   bit 1: has_spoiler_body — has a LEMMY_SPOILER_CONTENT span
        //   bits 2-7: reserved
        let flags: u32 = (self.all_ascii as u32) | ((self.has_spoiler_body as u32) << 1);
        let count_with_flags = (span_count as u32 & 0x00FF_FFFF) | (flags << 24);
        self.blob[0..4].copy_from_slice(&(txt_len as i32).to_le_bytes());
        self.blob[4..8].copy_from_slice(&count_with_flags.to_le_bytes());

        let padding = (4 - (txt_len % 4)) % 4;
        self.blob.extend_from_slice(&[0u8; 3][..padding]);

        let span_bytes = unsafe {
            std::slice::from_raw_parts(self.spans.as_ptr() as *const u8, self.spans.len() * 4)
        };
        self.blob.extend_from_slice(span_bytes);
        self.blob.extend_from_slice(&self.url_data);
        self.blob
    }
}

/// A container the walk is inside. Only containers are held, so nesting depth costs heap and
/// not call stack, as in upstream's formatters. The walk moves by the tree's own links, and the
/// held containers are always the current node's ancestors, so none needs its node.
struct Open {
    kind: Kind,
    start: usize,
    /// Span types it closes with; a negative type is an empty slot.
    spans: [i32; 2],
    /// The newline gap after it.
    gap: usize,
}

enum Kind {
    Plain,
    /// The next item's number.
    List(i32),
    /// The item's span type and data, until its own blocks are written and its nested lists are next.
    Item(Option<(i32, i32)>),
    Quote,
    /// The writer outside it.
    Footnote(Box<BlobWriter>),
    /// Where the text starts, and whether it stands in for a video.
    Link(usize, bool),
}

const NO_SPANS: [i32; 2] = [-1, -1];

thread_local! {
    /// The walk's stack from this thread's last render, so the next allocates none.
    static OPEN: RefCell<Vec<Open>> = const { RefCell::new(Vec::new()) };
}

pub(crate) fn visit<'a>(root: &'a AstNode<'a>, out: &mut BlobWriter) {
    let mut open = OPEN.take();
    walk(root, out, &mut open);
    OPEN.set(open);
}

fn walk<'a>(root: &'a AstNode<'a>, out: &mut BlobWriter, open: &mut Vec<Open>) {
    let (mut node, mut parent) = (root, root);
    loop {
        let held = open.len();
        enter(node, out, open);
        let mut after = (open.len() == held).then_some(node);
        if after.is_none() {
            parent = node;
        }
        loop {
            let Some(top) = open.last_mut() else {
                return;
            };
            if let Some(next) = next_child(parent, top, after, out) {
                node = next;
                break;
            }
            leave(parent, open.pop().unwrap(), out);
            after = Some(parent);
            parent = parent.parent().unwrap_or(root);
        }
    }
}

/// The child to walk after `after` (or the first), with any gap that goes before it.
fn next_child<'a>(
    node: &'a AstNode<'a>,
    o: &mut Open,
    after: Option<&'a AstNode<'a>>,
    out: &mut BlobWriter,
) -> Option<&'a AstNode<'a>> {
    let from = after.map_or_else(|| node.first_child(), |a| a.next_sibling());
    match &mut o.kind {
        Kind::Item(pending) => {
            let is_list = |c: &&AstNode<'a>| matches!(c.data.borrow().value, List(_));
            let siblings = |from| std::iter::successors(from, |c: &&AstNode<'a>| c.next_sibling());
            let mut next = siblings(from).find(|c| is_list(c) == pending.is_none());
            if next.is_none()
                && let Some((typ, data)) = pending.take()
            {
                out.span_data(typ, o.start, data);
                next = siblings(node.first_child()).find(is_list);
            }
            if next.is_some() && pending.is_none() {
                out.nl(1);
            }
            return next;
        }
        Kind::Quote if after.is_some() && from.is_some() => out.nl(2),
        _ => {}
    }
    from
}

/// Writes a node's opening, and holds it open when its children are to be walked.
fn enter<'a>(node: &'a AstNode<'a>, out: &mut BlobWriter, open: &mut Vec<Open>) {
    let val = &node.data.borrow().value;
    let start = out.pos();
    let hold = |open: &mut Vec<Open>, kind, start, spans, gap| {
        open.push(Open {
            kind,
            start,
            spans,
            gap,
        })
    };

    match val {
        List(l) => {
            let top_level = out.list_depth == 0;
            out.list_depth += 1;
            let number = match l.list_type {
                ListType::Ordered => l.start as i32,
                ListType::Bullet => 0,
            };
            hold(open, Kind::List(number), start, NO_SPANS, gap(top_level));
        }

        Item(_) | TaskItem(_) => {
            let indent = out.list_depth.saturating_sub(1);
            // Every item takes its ordinal, a task item too, so the next one numbers on. Ordered
            // starts go up to 999,999,999: clamped so they never spill into the indent bits.
            let number = match open.last_mut().map(|o| &mut o.kind) {
                Some(Kind::List(n)) => {
                    *n += (*n > 0) as i32;
                    (*n - (*n > 0) as i32).clamp(0, 0xFFFF)
                }
                _ => 0,
            };
            let (typ, low) = match val {
                TaskItem(ti) => (TASK_ITEM, ti.symbol.is_some() as i32),
                _ => (LIST_ITEM, number),
            };
            let data = ((indent as i32) << 16) | low;
            hold(open, Kind::Item(Some((typ, data))), start, NO_SPANS, 1);
        }

        BlockQuote => {
            let top_level = out.quote_depth == 0;
            out.quote_depth += 1;
            hold(open, Kind::Quote, start, NO_SPANS, gap(top_level));
        }

        Paragraph => {
            let top_level = !node.parent().is_some_and(|p| {
                matches!(p.data.borrow().value, BlockQuote | Item(_) | TaskItem(_))
            });
            // A paragraph of only &nbsp; is a pending gap like any other, so none trails the text
            if top_level
                && node
                    .children()
                    .all(|c| matches!(&c.data.borrow().value, Text(t) if t.chars().all(char::is_whitespace)))
            {
                out.p += 2;
            } else {
                hold(open, Kind::Plain, start, NO_SPANS, gap(top_level));
            }
        }

        Heading(h) => {
            let heading = HEADINGS[(h.level as usize).saturating_sub(1).min(5)];
            hold(open, Kind::Plain, start, [heading, BOLD], 2);
        }

        CodeBlock(c) => {
            // An empty block is nothing, with no gap of its own
            let code = c.literal.trim_end();
            if !code.is_empty() {
                out.write_text(code);
                out.span(CODE_BLOCK, start);
                out.nl(2);
            }
        }

        Table(_) => {
            out.write_text("View Table");
            out.span_table(start, node);
            out.nl(2);
        }

        ThematicBreak => {
            out.write_text("\u{0001}");
            out.span(HRULE, start);
            out.nl(2);
        }

        FootnoteReference(nfr) => {
            out.write_text(&nfr.ix.to_string());
            out.span(SUPERSCRIPT, start);
            out.span(SUPERSCRIPT_SIZE, start);
        }

        FootnoteDefinition(_) => {
            let outside = std::mem::replace(out, BlobWriter::new(64, false, out.site));
            hold(open, Kind::Footnote(Box::new(outside)), start, NO_SPANS, 0);
        }

        Text(t) => out.write_prose(&collapse_whitespace(t)),
        #[cfg(feature = "shortcodes")]
        ShortCode(sc) => out.write_text(&sc.emoji),
        Code(c) => {
            out.write_text(&c.literal);
            out.span(CODE, start);
        }

        // Safe-mode comrak discards raw HTML; keep the source as literal text so comments don't vanish.
        HtmlInline(h) => out.write_text(&prefer_ascii(&collapse_whitespace(h))),
        HtmlBlock(b) => {
            out.write_text(b.literal.trim_end());
            out.nl(2);
        }

        Image(l) => {
            let url = resolve_url(&l.url);
            if is_video_url(&url) {
                // A video in image syntax can't be embedded as an image. Render it as a
                // link instead: the alt text, or the URL itself when there is no alt.
                hold(open, Kind::Link(out.blob.len(), true), start, NO_SPANS, 0);
            } else {
                out.emit_image(&url);
            }
        }

        LineBreak => out.nl(1),
        SoftBreak => {
            if out.quote_depth > 0 {
                out.nl(1)
            } else if !out.at_line_start() {
                out.write_text(" ")
            }
        }

        Strong => hold(open, Kind::Plain, start, [BOLD, -1], 0),
        Emph => hold(open, Kind::Plain, start, [ITALIC, -1], 0),
        Strikethrough => hold(open, Kind::Plain, start, [STRIKETHROUGH, -1], 0),
        Superscript => hold(open, Kind::Plain, start, [SUPERSCRIPT, SUPERSCRIPT_SIZE], 0),
        Subscript => hold(open, Kind::Plain, start, [SUBSCRIPT, SUBSCRIPT_SIZE], 0),

        Link(l) => {
            let only = node.first_child().filter(|c| c.next_sibling().is_none());
            let wraps_image = only.is_some_and(|c| matches!(&c.data.borrow().value, Image(_)));
            let autolink = only.is_some_and(|c| {
                matches!(&c.data.borrow().value,
                Text(t) if t.starts_with("http://") || t.starts_with("https://"))
            });
            if wraps_image {
                hold(open, Kind::Plain, start, NO_SPANS, 0);
            } else if let Some(url) = autolink
                .then(|| resolve_url(&l.url))
                .filter(|u| is_image_url(u))
            {
                out.emit_image(&url);
            } else {
                hold(open, Kind::Link(out.blob.len(), false), start, NO_SPANS, 0);
            }
        }

        LemmySpoiler(ls) => {
            // Title: bold + 1.25x size (via BOLD + LINK_SIZE), plus LEMMY_SPOILER_TITLE for the
            // tap target and indicator. Title is plain text — no inline parsing.
            // Parser guarantees at least one child; empty-body spoilers are detached.
            out.write_text(&ls.title);
            out.span(BOLD, start);
            out.span(LINK_SIZE, start);
            out.span(LEMMY_SPOILER_TITLE, start);
            // Body span owns one trailing newline so the blank-line gap collapses with it.
            out.nl(1);
            hold(open, Kind::Plain, out.pos(), [LEMMY_SPOILER_CONTENT, -1], 2);
            out.nl(2);
        }

        _ => hold(open, Kind::Plain, start, NO_SPANS, 0),
    }
}

/// A top-level block's blank line after it.
fn gap(top_level: bool) -> usize {
    if top_level { 2 } else { 0 }
}

/// Writes a container's closing once its children are done.
fn leave<'a>(node: &'a AstNode<'a>, o: Open, out: &mut BlobWriter) {
    match o.kind {
        Kind::List(_) => out.list_depth -= 1,
        Kind::Quote => {
            out.quote_depth -= 1;
            out.span_data(QUOTE, o.start, out.quote_depth as i32);
        }
        Kind::Footnote(outside) => {
            let tmp = std::mem::replace(out, *outside);
            out.footnotes.push(tmp.text().trim().to_string());
        }
        Kind::Link(text_start, video) => {
            let (Link(l) | Image(l)) = &node.data.borrow().value else {
                unreachable!()
            };
            let url = resolve_url(&l.url);
            if video && out.blob.len() == text_start {
                out.write_text(&url);
            }
            out.link(o.start, text_start, &url);
        }
        Kind::Plain | Kind::Item(_) => {}
    }
    for t in o.spans {
        if t >= 0 {
            out.span(t, o.start);
        }
    }
    out.nl(o.gap);
}

/// `fmt::Write` over the url section, so a table cell's markdown lands there without a String
struct Utf8Sink<'a>(&'a mut Vec<u8>);

impl std::fmt::Write for Utf8Sink<'_> {
    fn write_str(&mut self, s: &str) -> std::fmt::Result {
        self.0.extend_from_slice(s.as_bytes());
        Ok(())
    }
}
